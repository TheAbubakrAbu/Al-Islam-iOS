import Foundation

// Hamzat al-wasl in the OTHER notation, for every riwayah text the app ships.
//
// Two conventions write the connecting alef. The Madinah-style texts (Hafs and eleven more) put a
// small saad on it, U+0671. The Maghribi-style texts (Qaloon, Warsh, Duri, Susi, Ibn Wardan, Ibn
// Jammaz, Ruways, Rawh) write a bare alef carrying the JOIN vowel (what the previous word ends on)
// and a START sign: U+06EC filled dot above = start with a fatha (the article), U+06EA hollow ring
// below = kasra (ibn, ism, ittaqu), U+06DF small circle above = damma (udkhulu, unzur); after a
// one-letter prefix (wa-, bi-, fa-...) the alef stays bare. The reader can ask for either notation
// on any text (`Settings.WaslSignStyle`).
//
// Nothing linguistic happens here. Which alef changes, which vowel it takes and which sign it
// carries were all decided by Quran-Tajweed-Engine/scripts/al-islam/build_wasl_signs.py (the join
// vowel from the previous word across ayah ends and from the basmalah, the sign from the verified
// dot texts, the tanween-before-damma khilaf per reader) and shipped as `WaslSigns.json.xz`: one
// character per word of the shipped text. This file only applies those codes:
//
//   .      the word is unchanged
//   0      its first U+0671 becomes a bare alef (a prefixed wasl, Madani style)
//   1..9   its first U+0671 becomes alef + join vowel + start sign, code = 1 + 3*join + start
//          with a=0, i=1, u=2 for both; any later U+0671 in the word becomes a bare alef
//   A..J   the alef that is letter number 0..9 of the word (marks not counted) becomes U+0671 and
//          up to two following short vowels / wasl signs are dropped
//   T      letters 0 and 2 both (49:11 al-ismu: the article before another wasl alef)
//
// `WaslSignTransform.apply` mirrors the script's `splice` exactly; `UnitTests/WaslSignSamples.swift`
// (generated by the same script) holds the engine's own output for 150 ayahs, and
// `WaslSignTests` checks the two agree.

extension Settings {
    /// Which hamzat al-wasl notation the Quran text shows. `.print` is the default: every riwayah
    /// as its printed mushaf writes it (the saad in the Madinah prints, the dot in the Maghribi
    /// ones). `.saad` and `.dot` apply one notation to every text.
    enum WaslSignStyle: String, CaseIterable, Identifiable {
        case print, saad, dot
        var id: String { rawValue }

        var label: String {
            switch self {
            case .print: return String(localized: "Follow the Print")
            case .saad: return String(localized: "Saad")
            case .dot: return String(localized: "Dot")
            }
        }

        /// Caption under the picker.
        var detail: String {
            switch self {
            case .print:
                return String(localized: "Each riwayah writes the connecting alef the way its printed mushaf does: a small saad on the alef in the Madinah prints, a dot with the joining vowel in the Maghribi ones.")
            case .saad:
                return String(localized: "The small saad on the connecting alef, as in the Madinah mushaf, on every riwayah.")
            case .dot:
                return String(localized: "The Maghribi notation on every riwayah: the alef carries the vowel you arrive on, and a dot above it (start with a fatha), a ring below (kasra) or a small circle above (damma) tells how to start on it.")
            }
        }
    }

    /// The stored choice (`quranWaslSign`); empty means never chosen, which is Follow the Print.
    var waslSignStyle: WaslSignStyle {
        get { WaslSignStyle(rawValue: waslSignRaw) ?? .print }
        set { waslSignRaw = newValue.rawValue }
    }

    /// The notation a riwayah's text actually renders with. One correction over the stored value:
    /// the Warsh face has no glyph for U+0671, so a text set in it (the Maghribi script style, or
    /// Automatic on Nafi's pair) keeps the dot whatever the picker says.
    func waslSign(for qiraah: String?) -> WaslSignStyle {
        let style = waslSignStyle
        guard style == .saad else { return style }
        return quranArabicFontName(for: qiraah) == Settings.warshUthmaniFontName ? .print : style
    }
}

/// The per-word codes of `WaslSigns.json.xz`, loaded once on first use and resident after that
/// (about two megabytes of short strings for the twenty texts).
final class WaslSignStore: @unchecked Sendable {
    static let shared = WaslSignStore()
    private init() {}

    private struct TextCodes {
        /// "dot" when the codes turn this (saad) text into the dot notation, "saad" the other way.
        let to: String
        /// surah id -> ayah id -> one code character per word.
        let surahs: [Int: [Int: String]]
    }

    private let lock = NSLock()
    private var loaded: [String: TextCodes]?
    private var loadFailed = false

    /// The sidecar's key for a display riwayah: the app's canonical tag, "Hafs" for the default.
    static func key(for qiraah: String?) -> String {
        guard let qiraah, !qiraah.isEmpty, qiraah != "Hafs" else { return "Hafs" }
        let tag = Settings.Riwayah.canonicalTag(qiraah)
        return tag.isEmpty ? "Hafs" : tag
    }

    /// The codes that take this ayah of this riwayah INTO `style`, or nil when the text already
    /// is in that notation, has no wasl alef in this ayah, or the sidecar is not bundled.
    func codes(qiraah: String?, surah: Int, ayah: Int, style: Settings.WaslSignStyle) -> String? {
        guard style != .print, let table = table() else { return nil }
        guard let text = table[Self.key(for: qiraah)], text.to == style.rawValue else { return nil }
        return text.surahs[surah]?[ayah]
    }

    private func table() -> [String: TextCodes]? {
        lock.lock(); defer { lock.unlock() }
        if let loaded { return loaded }
        if loadFailed { return nil }
        guard let parsed = Self.load() else { loadFailed = true; return nil }
        loaded = parsed
        return parsed
    }

    private static func load() -> [String: TextCodes]? {
        guard let url = Bundle.main.url(forResource: "WaslSigns", withExtension: "json.xz")
                ?? Bundle.main.url(forResource: "WaslSigns", withExtension: "json.xz", subdirectory: "Data/Quran"),
              let blob = try? Data(contentsOf: url),
              let json = SolidPack.xzDecompress(blob),
              let root = try? JSONSerialization.jsonObject(with: json) as? [String: Any],
              let texts = root["texts"] as? [String: [String: Any]] else { return nil }
        var out: [String: TextCodes] = [:]
        out.reserveCapacity(texts.count)
        for (tag, entry) in texts {
            guard let to = entry["to"] as? String, let surahs = entry["surahs"] as? [String: [String: String]] else { continue }
            var bySurah: [Int: [Int: String]] = [:]
            bySurah.reserveCapacity(surahs.count)
            for (sid, ayahs) in surahs {
                guard let s = Int(sid) else { continue }
                var byAyah: [Int: String] = [:]
                byAyah.reserveCapacity(ayahs.count)
                for (aid, code) in ayahs {
                    if let a = Int(aid) { byAyah[a] = code }
                }
                bySurah[s] = byAyah
            }
            out[tag] = TextCodes(to: to, surahs: bySurah)
        }
        return out.isEmpty ? nil : out
    }
}

/// The splice: the script's `splice` in Swift, over unicode scalars (a space followed by a
/// combining mark is still a word gap here, which `Character` splitting would hide).
enum WaslSignTransform {
    static let wasla: Unicode.Scalar = "\u{0671}"
    static let alef: Unicode.Scalar = "\u{0627}"
    static let fatha: Unicode.Scalar = "\u{064E}"
    static let damma: Unicode.Scalar = "\u{064F}"
    static let kasra: Unicode.Scalar = "\u{0650}"
    static let dotAbove: Unicode.Scalar = "\u{06EC}"
    static let ringBelow: Unicode.Scalar = "\u{06EA}"
    static let circleAbove: Unicode.Scalar = "\u{06DF}"

    private static let vowels: [Unicode.Scalar] = [fatha, kasra, damma]          // a, i, u
    private static let signs: [Unicode.Scalar] = [dotAbove, ringBelow, circleAbove]

    /// What a saad collapse drops after the alef: the join vowel and the start sign.
    static func isVowelOrSign(_ s: Unicode.Scalar) -> Bool {
        switch s.value {
        case 0x064E, 0x064F, 0x0650, 0x06EC, 0x06EA, 0x06DF: return true
        default: return false
        }
    }

    /// The letters the A..J codes count: the Arabic letters, the wasla, and the dotless skeleton
    /// glyphs Hide Arabic Dots draws (so a letter index holds under that option too).
    static func isLetter(_ s: Unicode.Scalar) -> Bool {
        switch s.value {
        case 0x0621...0x063A, 0x0641...0x064A, 0x0671, 0x066E, 0x066F, 0x06A1, 0x06BA, 0x06CC, 0x067E: return true
        default: return false
        }
    }

    /// The scalars a dot-form code puts in place of the word's first U+0671.
    static func expansion(forCode code: Character) -> [Unicode.Scalar]? {
        guard let ascii = code.asciiValue, ascii >= 0x30, ascii <= 0x39 else { return nil }
        if ascii == 0x30 { return [alef] }
        let n = Int(ascii - 0x31)
        return [alef, vowels[n / 3], signs[n % 3]]
    }

    /// `text` with `codes` applied, one code per space-separated word.
    static func apply(_ text: String, codes: String) -> String {
        guard !codes.isEmpty else { return text }
        let codeChars = Array(codes)
        var out = String.UnicodeScalarView()
        out.reserveCapacity(text.unicodeScalars.count + 64)
        var word: [Unicode.Scalar] = []
        var wordIndex = 0

        func flush() {
            let code: Character = wordIndex < codeChars.count ? codeChars[wordIndex] : "."
            out.append(contentsOf: transformed(word, code: code))
            word.removeAll(keepingCapacity: true)
            wordIndex += 1
        }

        for scalar in text.unicodeScalars {
            if scalar.value == 0x20 {
                flush()
                out.append(scalar)
            } else {
                word.append(scalar)
            }
        }
        flush()
        return String(out)
    }

    /// One word under one code.
    static func transformed(_ word: [Unicode.Scalar], code: Character) -> [Unicode.Scalar] {
        if code == "." || word.isEmpty { return word }
        if let expansion = expansion(forCode: code) {
            guard let first = word.firstIndex(of: wasla) else { return word }
            var result = Array(word[..<first])
            result.append(contentsOf: expansion)
            for scalar in word[(first + 1)...] {
                result.append(scalar == wasla ? alef : scalar)
            }
            return result
        }
        let indices: [Int]
        if code == "T" {
            indices = [2, 0]                       // later site first: a collapse's deletions never shift an earlier index
        } else if let ascii = code.asciiValue, ascii >= 0x41, ascii <= 0x4A {
            indices = [Int(ascii - 0x41)]
        } else {
            return word
        }
        var chars = word
        for letterIndex in indices {
            guard let ci = charIndex(ofLetter: letterIndex, in: chars), chars[ci] == alef else { continue }
            chars[ci] = wasla
            var dropped = 0
            while ci + 1 < chars.count, dropped < 2, isVowelOrSign(chars[ci + 1]) {
                chars.remove(at: ci + 1)
                dropped += 1
            }
        }
        return chars
    }

    private static func charIndex(ofLetter letterIndex: Int, in chars: [Unicode.Scalar]) -> Int? {
        var seen = 0
        for (i, s) in chars.enumerated() where isLetter(s) {
            if seen == letterIndex { return i }
            seen += 1
        }
        return nil
    }
}
